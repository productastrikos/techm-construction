import { launch, openPage, outDir } from './lib.mjs';
const lang = process.argv[2] || 'en';
const browser = await launch();
const dir = outDir('flows');
const { ctx, page, log } = await openPage(browser, { w: 1366, h: 768, lang, route: '/whatif/supply' });
await page.waitForTimeout(2500);
await page.click('button[aria-pressed]:has-text("Closed"), button[aria-pressed]:has-text("مغلق")');
await page.waitForTimeout(2500);
await page.click('[data-testid="view-gantt"]');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${dir}/h1_gantt_noaction_${lang}.png` });
await page.click('a[href="#/twin"]');
await page.waitForTimeout(3000);
await page.evaluate(() => { window.__twin.getState().setViewT(330); });
await page.waitForTimeout(3500);
await page.click('[data-testid="cam-quay"]');
await page.waitForTimeout(3500);
await page.screenshot({ path: `${dir}/h1_twin_noaction_${lang}.png` });
console.log(JSON.stringify({ errors: log.errors, pageErrors: log.pageErrors }));
await browser.close();
